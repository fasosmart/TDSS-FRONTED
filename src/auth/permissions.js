// Déduit la clé de rôle (`type_code|profile_type_code`) à partir du user `/me`.
export function getRoleKey(user) {
  const typeCode = user?.type_code?.toLowerCase().trim();
  const profileCode = user?.companies?.[0]?.type_code?.toLowerCase().trim();
  if (!typeCode) return null;
  return profileCode ? `${typeCode}|${profileCode}` : typeCode;
}

// Permissions par défaut (fallback) pour un user, dérivées du `type_code`.
export function getDefaultPermissions(user) {
  const typeCode = user?.type_code?.toLowerCase().trim();
  if (!typeCode) return {};

  const key = getRoleKey(user);
  if (key && ROLE_DEFAULT_PERMISSIONS[key]) return ROLE_DEFAULT_PERMISSIONS[key];

  // Pas de company exploitable : si un seul profil correspond au type, l'utiliser.
  const matches = Object.keys(ROLE_DEFAULT_PERMISSIONS).filter((k) => k.startsWith(`${typeCode}|`));
  if (matches.length === 1) return ROLE_DEFAULT_PERMISSIONS[matches[0]];

  return {};
}
